"""Regenerate the embedded catalog from a pinned, MIT-licensed CSGO-API snapshot."""
import argparse
import hashlib
import json
from collections import defaultdict
from pathlib import Path
import urllib.request

SOURCE_COMMIT = '575aa6ff5bde0d23b32f385d1f612d55aa22df56'
SOURCE_ROOT = f'https://raw.githubusercontent.com/ByMykel/CSGO-API/{SOURCE_COMMIT}'
ROOT = Path(__file__).resolve().parents[1]
TRACKER_COMMIT = 'e2b28ef14cf41d5422b74875088ee8dc9dac5ef1'
# The API's old raw GitHub URL for this item is gone. The pinned image tracker
# maps the same Train Gold artwork's _1355_37 variant to Valve's CDN.
TRAIN_GOLD_URL = ('https://cdn.steamstatic.com/apps/730/icons/econ/stickers/tournament_assets/'
                  'de_train_gold_1355_37.96748389bb2fb2885fd60bfaaf821121544449e9.png')


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-file', type=Path, help='Previously downloaded snapshot')
    parser.add_argument('--source-dir', type=Path, help='Directory containing cached cs2-<endpoint>.json snapshots')
    args = parser.parse_args()
    hashes = {}
    def source(name):
        cached = args.source_file if name == 'skins' and args.source_file else (
            args.source_dir / f'cs2-{name}.json' if args.source_dir else None)
        if cached and cached.exists():
            raw = cached.read_bytes()
        else:
            with urllib.request.urlopen(SOURCE_ROOT + f'/public/api/en/{name}.json', timeout=60) as response:
                raw = response.read()
        hashes[name] = hashlib.sha256(raw).hexdigest()
        return json.loads(raw)
    images, image_urls = [], {}
    def image(filename, url):
        allowed = ('https://community.akamai.steamstatic.com/economy/image/',
                   'https://cdn.steamstatic.com/apps/730/icons/')
        if not url.startswith(allowed):
            raise ValueError(f'Unexpected image destination: {url}')
        if url in image_urls:
            return image_urls[url]
        image_urls[url] = filename
        images.append(dict(file=filename, url=url))
        return filename
    records, seen = [], set()
    for item in source('skins'):
        definition = int(item['weapon']['weapon_id'])
        paint = int(item['paint_index'] or 0)
        if (definition, paint) in seen:
            raise ValueError(f'Duplicate definition/paint pair: {definition}/{paint}')
        seen.add((definition, paint))
        category_id = item['category']['id']
        category = ('Knife' if category_id == 'sfui_invpanel_filter_melee' else
                    'Gloves' if category_id == 'sfui_invpanel_filter_gloves' else 'Weapon')
        finish = (item.get('pattern') or {}).get('name', 'Vanilla')
        if item.get('phase'):
            finish += ' - ' + item['phase']
        records.append(dict(definition=definition, paint=paint, category=category,
                            model=item['weapon']['name'], finish=finish,
                            min_wear=item['min_float'] or 0,
                            max_wear=item['max_float'] if item['max_float'] is not None else 1,
                            rarity=item['rarity']['color'], file=image(f'{definition}_{paint}.png', item['image'])))
    records.sort(key=lambda x: (x['definition'], x['finish'].casefold(), x['paint']))
    wear_rows = defaultdict(list)
    for item in source('skins_not_grouped'):
        if not item.get('stattrak') and item.get('wear'):
            wear_rows[(int(item['weapon']['weapon_id']), int(item['paint_index'] or 0))].append(item)
    lines = ['// Generated by tools/update_catalog.py. Source attribution: licenses/CSGO-API.txt.']
    for entry in records:
        tiers = [None] * 5
        variants = wear_rows[(entry['definition'], entry['paint'])]
        normal = [item for item in variants if not item.get('souvenir')]
        for variant in normal or variants:
            state = int(variant['wear']['id'].rsplit('_', 1)[1])
            filename = image(f"{entry['definition']}_{entry['paint']}_w{state}.png", variant['image'])
            if tiers[state] and tiers[state] != filename:
                raise ValueError(f'Ambiguous wear preview for {entry["definition"]}/{entry["paint"]}')
            tiers[state] = filename
        low, high = f"{entry['min_wear']:.8f}f", f"{entry['max_wear']:.8f}f"
        tier_data = ', '.join(quote(value) if value else 'nullptr' for value in tiers)
        lines.append('{%d, %d, Category::%s, %s, %s, %s, %s, %s, 0x%su, {%s}},' % (
            entry['definition'], entry['paint'], entry['category'], quote(entry['model']),
            quote(entry['finish']), quote(entry['file']), low, high, entry['rarity'][1:], tier_data))
    (ROOT / 'src/generated').mkdir(parents=True, exist_ok=True)
    (ROOT / 'src/generated/skins.inc').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    items = []
    for endpoint, category, prefix in [('agents', 'Agent', 'agent'), ('music_kits', 'Music', 'music'),
                                       ('stickers', 'Sticker', 'sticker'), ('keychains', 'Charm', 'charm')]:
        grouped = defaultdict(list)
        for item in source(endpoint):
            grouped[int(item['def_index'])].append(item)
        for identifier, variants in grouped.items():
            base = next((v for v in variants if not v['id'].endswith('_st')), variants[0])
            stattrak = next((v for v in variants if v['id'].endswith('_st')), None)
            url = TRAIN_GOLD_URL if category == 'Sticker' and identifier == 8553 else base['image']
            filename = image(f'{prefix}_{identifier}.png', url)
            st_filename = image(f'{prefix}_{identifier}_st.png', stattrak['image']) if stattrak else None
            name = base['name']
            for label in ('Music Kit | ', 'Sticker | ', 'Charm | '):
                if name.startswith(label): name = name[len(label):]
            group = (base.get('team', {}).get('name') if category == 'Agent' else
                     base.get('effect') if category == 'Sticker' else
                     (base.get('collections') or [{}])[0].get('name') if category == 'Charm' else 'Music kit')
            items.append(dict(category=category, id=identifier, name=name, group=group or '',
                              file=filename, st_file=st_filename, rarity=base['rarity']['color']))
    items.sort(key=lambda item: (item['category'], item['name'].casefold(), item['id']))
    item_lines = ['// Generated by tools/update_catalog.py. Source attribution: licenses/CSGO-API.txt.']
    for item in items:
        item_lines.append('{Category::%s, %d, %s, %s, %s, %s, 0x%su},' % (
            item['category'], item['id'], quote(item['name']), quote(item['group']), quote(item['file']),
            quote(item['st_file']) if item['st_file'] else 'nullptr', item['rarity'][1:]))
    (ROOT / 'src/generated/items.inc').write_text('\n'.join(item_lines) + '\n', encoding='utf-8')
    manifest = dict(source_commit=SOURCE_COMMIT, source_sha256=hashes,
                    image_override_source=f'ByMykel/counter-strike-image-tracker@{TRACKER_COMMIT}', images=images)
    (ROOT / 'assets').mkdir(exist_ok=True)
    (ROOT / 'assets/preview-manifest.json').write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    (ROOT / 'licenses').mkdir(exist_ok=True)
    with urllib.request.urlopen(SOURCE_ROOT + '/LICENSE', timeout=30) as response:
        (ROOT / 'licenses/CSGO-API.txt').write_bytes(response.read())
    print(f'Generated {len(records)} finishes / {len({r["definition"] for r in records})} models')
    print(f'Generated {len(items)} other items; {len(images)} unique images including wear states')


if __name__ == '__main__':
    main()
