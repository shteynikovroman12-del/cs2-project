"""Regenerate the embedded catalog from a pinned, MIT-licensed CSGO-API snapshot."""
import argparse
import hashlib
import json
from pathlib import Path
import urllib.request

SOURCE_COMMIT = '575aa6ff5bde0d23b32f385d1f612d55aa22df56'
SOURCE_ROOT = f'https://raw.githubusercontent.com/ByMykel/CSGO-API/{SOURCE_COMMIT}'
ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-file', type=Path, help='Previously downloaded snapshot')
    args = parser.parse_args()
    if args.source_file:
        raw = args.source_file.read_bytes()
    else:
        with urllib.request.urlopen(SOURCE_ROOT + '/public/api/en/skins.json', timeout=60) as response:
            raw = response.read()
    records, seen = [], set()
    for item in json.loads(raw):
        definition = int(item['weapon']['weapon_id'])
        paint = int(item['paint_index'] or 0)
        if (definition, paint) in seen:
            raise ValueError(f'Duplicate definition/paint pair: {definition}/{paint}')
        seen.add((definition, paint))
        category_id = item['category']['id']
        category = ('Knife' if category_id == 'sfui_invpanel_filter_melee' else
                    'Gloves' if category_id == 'sfui_invpanel_filter_gloves' else 'Weapon')
        finish = (item.get('pattern') or {}).get('name', 'Vanilla')
        if item.get('phase'):
            finish += ' - ' + item['phase']
        url = item['image']
        if not url.startswith('https://community.akamai.steamstatic.com/economy/image/'):
            raise ValueError('Unexpected image destination')
        records.append(dict(definition=definition, paint=paint, category=category,
                            model=item['weapon']['name'], finish=finish,
                            min_wear=item['min_float'] or 0,
                            max_wear=item['max_float'] if item['max_float'] is not None else 1,
                            rarity=item['rarity']['color'], file=f'{definition}_{paint}.png', url=url))
    records.sort(key=lambda x: (x['definition'], x['finish'].casefold(), x['paint']))
    lines = ['// Generated by tools/update_catalog.py. Source attribution: licenses/CSGO-API.txt.']
    for entry in records:
        quote = lambda text: json.dumps(text, ensure_ascii=False)
        low, high = f"{entry['min_wear']:.8f}f", f"{entry['max_wear']:.8f}f"
        lines.append('{%d, %d, Category::%s, %s, %s, %s, %s, %s, 0x%su},' % (
            entry['definition'], entry['paint'], entry['category'], quote(entry['model']),
            quote(entry['finish']), quote(entry['file']), low, high, entry['rarity'][1:]))
    (ROOT / 'src/generated').mkdir(parents=True, exist_ok=True)
    (ROOT / 'src/generated/skins.inc').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    manifest = dict(source_commit=SOURCE_COMMIT, source_sha256=hashlib.sha256(raw).hexdigest(),
                    images=[{key: entry[key] for key in ('file', 'url')} for entry in records])
    (ROOT / 'assets').mkdir(exist_ok=True)
    (ROOT / 'assets/preview-manifest.json').write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    (ROOT / 'licenses').mkdir(exist_ok=True)
    with urllib.request.urlopen(SOURCE_ROOT + '/LICENSE', timeout=30) as response:
        (ROOT / 'licenses/CSGO-API.txt').write_bytes(response.read())
    print(f'Generated {len(records)} finishes / {len({r["definition"] for r in records})} models')


if __name__ == '__main__':
    main()
